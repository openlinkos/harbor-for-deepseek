// Inner sidebar pieces: header, history list, select bar, collapsed pill, avatar.
import { expect, test, type Page, type Route } from '@playwright/test'

const install = async (page: Page) => {
  await page.route('https://api.deepseek.com/**', async (route: Route) => {
    const url = route.request().url()
    if (url.endsWith('/user/balance')) return route.fulfill({ json: { is_available: true, balance_infos: [{ currency: 'CNY', total_balance: '1', granted_balance: '0', topped_up_balance: '1' }] } })
    if (url.endsWith('/models')) return route.fulfill({ json: { data: [{ id: 'deepseek-flash' }] } })
    return route.fulfill({ status: 404, json: {} })
  })
}

const seed = async (page: Page) => {
  await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((ok, ko) => {
      const request = indexedDB.open('deepapi')
      request.onsuccess = () => ok(request.result)
      request.onerror = () => ko(request.error)
    })
    const tx = db.transaction(['conversations', 'messages'], 'readwrite')
    const id = crypto.randomUUID()
    const mid = crypto.randomUUID()
    const when = new Date().toISOString()
    tx.objectStore('conversations').put({ id, title: '侧栏测量', titleSource: 'user', model: 'deepseek-flash', thinking: false, search: false, readLink: false, effort: 'high', pinned: false, archived: false, activeLeafId: mid, createdAt: when, updatedAt: when, rev: 1, deletedAt: null })
    tx.objectStore('messages').put({ id: mid, conversationId: id, parentId: null, role: 'user', blocks: [{ type: 'text', text: '你好' }], status: 'complete', usage: null, errorMessage: null, createdAt: when, updatedAt: when, rev: 1, deletedAt: null })
    await new Promise((ok, ko) => { tx.oncomplete = () => ok(null); tx.onerror = () => ko(tx.error) })
    db.close()
  })
  await page.reload()
}

test('sidebar header, list, select bar, and collapsed pill match the inner pieces', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await install(page)
  await page.goto('/')
  await page.getByTestId('landing-send').click()
  await page.getByTestId('key-input').fill('demo-local-key')
  await page.getByTestId('key-save').click()
  await expect(page.getByTestId('composer')).toBeVisible()

  const top = page.locator('.sider-top')
  await expect(top).toHaveCSS('height', '48px')
  await expect(top).toHaveCSS('padding', '15px 0px 10px 4px')
  await expect(top).toHaveCSS('margin-bottom', '16px')
  await expect(top).toHaveCSS('justify-content', 'space-between')
  await expect(page.locator('.sider-icons')).toHaveCSS('gap', '18px')
  await expect(page.locator('.sider-icons .icon-btn').first()).toHaveCSS('color', 'rgb(129, 133, 140)')
  const empty = page.locator('.side-scroll > .hint')
  await expect(empty).toHaveCSS('font-size', '12px')
  await expect(empty).toHaveCSS('line-height', '18px')
  await expect(empty).toHaveCSS('font-weight', '500')
  await expect(empty).toHaveCSS('color', 'rgb(129, 133, 140)')
  await expect(page.locator('.side-scroll-wrap')).toHaveCSS('margin-top', '24px')
  await expect(page.locator('.side-scroll')).toHaveCSS('margin-top', '0px')
  await expect(page.locator('.side-scroll')).toHaveCSS('margin-left', '-2px')
  await expect(page.locator('.side-scroll')).toHaveCSS('margin-right', '-2px')
  await expect(page.locator('.side-scroll')).toHaveCSS('overflow-x', 'auto')
  await expect(page.locator('.side-scroll')).toHaveCSS('overflow-y', 'auto')
  const avatar = page.locator('.user-bar .avatar')
  await expect(avatar).toHaveCSS('width', '32px')
  await expect(avatar).toHaveCSS('height', '32px')
  await expect(avatar).toHaveCSS('background-color', 'rgba(0, 0, 0, 0.04)')
  await expect(page.locator('.user-bar')).toHaveCSS('height', '44px')
  await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''))
  await expect(avatar).toHaveCSS('background-color', 'rgba(255, 255, 255, 0.08)')
  await page.evaluate(() => document.body.removeAttribute('data-ds-dark-theme'))

  await seed(page)
  await page.getByRole('button', { name: '多选' }).click()
  const head = page.locator('.select-head')
  await expect(head).toHaveCSS('height', '40px')
  await expect(head).toHaveCSS('padding', '0px 0px 0px 10px')
  await expect(head).toHaveCSS('font-size', '16px')
  await expect(head).toHaveCSS('font-weight', '500')
  await expect(head).toHaveCSS('line-height', '24px')
  const close = page.locator('.select-close')
  await expect(close).toHaveCSS('width', '28px')
  await expect(close).toHaveCSS('height', '28px')
  await expect(close).toHaveCSS('border-top-width', '1px')
  await expect(close).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(close).toHaveCSS('color', 'rgb(97, 102, 107)')
  await close.hover()
  await expect(close).toHaveCSS('background-color', 'rgb(241, 243, 245)')
  const foot = page.locator('.select-foot')
  await expect(foot).toHaveCSS('height', '62px')
  await expect(foot).toHaveCSS('border-top-width', '1px')
  const danger = foot.getByRole('button', { name: '删除' })
  await expect(danger).toHaveCSS('color', 'rgb(173, 178, 184)')
  await expect(danger).toHaveCSS('gap', '8px')
  await expect(danger).toHaveCSS('line-height', '22px')

  await page.locator('.sidebar').getByRole('button', { name: '隐藏' }).click()
  const pill = page.locator('.float-pill')
  await expect(pill).toHaveCSS('height', '40px')
  await expect(pill).toHaveCSS('border-radius', '100px')
  await expect(pill).toHaveCSS('padding-right', '3px')
  await expect(pill).toHaveCSS('gap', '2px')
  await expect(pill).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(pill).toHaveCSS('border-top-color', 'rgba(0, 0, 0, 0.1)')
  await expect(page.locator('.collapsed-mark')).toHaveCSS('width', '27px')
  await expect(page.locator('.collapsed-mark')).toHaveCSS('height', '24px')
  await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''))
  await expect(pill).toHaveCSS('background-color', 'rgb(53, 54, 56)')
  await expect(pill).toHaveCSS('border-top-color', 'rgba(255, 255, 255, 0.12)')
})
