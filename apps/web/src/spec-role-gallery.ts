export const mountSpecRoleGallery = () => {
  if (typeof document === 'undefined') return
  if (document.getElementById('ds-spec-role-gallery')) return
  const host = document.createElement('div')
  host.id = 'ds-spec-role-gallery'
  host.setAttribute('aria-hidden', 'true')
  host.setAttribute('inert', '')
  for (const row of specRoleRows) {
    const node = document.createElement('div')
    node.dataset.sp = row.id
    if (row.className) node.className = row.className
    host.appendChild(node)
  }
  document.body.appendChild(host)
}
